import assert from 'node:assert/strict';
// Browser configuration is supplied before importing the browser modules.
if (!globalThis.location) globalThis.location={hostname:'localhost',port:'8000',origin:'http://localhost:8000',search:''};
const {tripDays,factQuery,tripFromQuery,tripToQuery}=await import('../js/trip.js');
const {filterFacts}=await import('../js/api.js');
const {toPayload,fromRow,savedChecks}=await import('../js/saved-trips.js');
assert.equal(tripDays({from:'2027-03-15',to:'2027-03-28'}),14);
assert.equal(tripDays({from:'2028-02-28',to:'2028-03-01'}),3);
assert.equal(tripDays({from:'2027-03-28',to:'2027-03-15'}),null);
assert.equal(factQuery({from:'2027-03-15',to:'2027-03-28',purpose:'leisure'}).purpose,'tourism');
assert.equal(factQuery({purpose:'emergency'}).purpose,null);
assert.equal(tripDays({from:'2027-02-30',to:'2027-03-02'}),null);
const general={id:'general',applicability_status:'general'};
const tourism={id:'tourism',applicability_status:'conditional',min_stay_days:1,max_stay_days:90,applies_to_purposes:['tourism']};
const work={id:'work',applicability_status:'conditional',applies_to_purposes:['work']};
const draft={id:'draft',applicability_status:'needs_review'};
assert.deepEqual(filterFacts([general,tourism,work,draft]).map(x=>x.id),['general']);
assert.deepEqual(filterFacts([general,tourism,work,draft],{stayMin:14,stayMax:14,purpose:'tourism'}).map(x=>x.id),['general','tourism']);
assert.deepEqual(filterFacts([general,tourism,work],{stayMin:120,stayMax:120,purpose:'work'}).map(x=>x.id),['general','work']);
const trip={id:'11111111-1111-4111-8111-111111111111',country:'japan',name:'Japan test',purpose:'leisure',from:'2027-03-15',to:'2027-03-28',description:'private'};
const payload=toPayload(trip,new Set([0,7]));
assert.equal(payload.trip_purpose,'tourism');
assert.equal(payload.destination_slug,'japan');
assert.deepEqual(payload.completed_checklist,{'task-0':true,'task-7':true});
for(const key of ['id','owner_id','email','password','description','trip_description'])assert.equal(key in payload,false);
assert.equal(fromRow({...payload,id:trip.id}).purpose,'leisure');
assert.deepEqual(savedChecks({completed_checklist:{'task-0':true,'task-7':true,'task-9':true,'task-1':false,unknown:true}}),[0,7]);
const query=tripToQuery(trip);assert.ok(!query.includes('private'));assert.equal(tripFromQuery(query).id,trip.id);
console.log('Frontend checks passed: duration, purpose, snapshot eligibility, save payload, checklist restoration and saved-trip route.');
